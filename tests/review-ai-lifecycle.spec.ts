import {test,expect} from '@playwright/test';
import {command} from '../packages/sim/src';
import {exportSave} from '../packages/save/src';
import {aiFixture,serviceConfig} from './review-fixture';
import {nav} from './ui-helpers';

test('AI archive and disposal require confirmation and retain history after saving',async({page})=>{
 const state=command(aiFixture(),serviceConfig);
 await page.setViewportSize({width:844,height:390});await page.goto('/');
 await page.getByLabel('JSON読み込み').setInputFiles({name:'ai.json',mimeType:'application/json',buffer:Buffer.from(exportSave(state))});
 await nav(page,'AI Lab');
 await page.getByRole('tab',{name:'モデル',exact:true}).click();
 await expect(page.getByRole('button',{name:'履歴へ移す…',exact:true})).toBeDisabled();
 await page.getByRole('tab',{name:'クラスタ',exact:true}).click();
 await expect(page.getByRole('button',{name:'撤去…',exact:true})).toBeDisabled();
 await page.getByRole('tab',{name:'モデル',exact:true}).click();
 await page.getByRole('button',{name:'サービスを停止',exact:true}).click();
 await page.getByRole('button',{name:'履歴へ移す…',exact:true}).click();
 const archive=page.getByRole('group',{name:'履歴へ移すの確認'});
 await expect(archive).toContainText('再開できなくなります');
 await archive.getByRole('button',{name:'やめる',exact:true}).click();
 await expect(page.getByTestId('model-status-m-1')).toBeVisible();
 await page.getByRole('button',{name:'履歴へ移す…',exact:true}).click();
 await archive.getByRole('button',{name:'履歴へ移すを確定',exact:true}).click();
 await expect(page.getByTestId('model-status-m-1')).toHaveCount(0);
 await page.getByRole('tab',{name:'クラスタ',exact:true}).click();
 await page.getByRole('button',{name:'撤去…',exact:true}).click();
 const disposal=page.getByRole('group',{name:'撤去の確認'});
 await expect(disposal).toContainText('在庫は戻りません');
 await disposal.getByRole('button',{name:'やめる',exact:true}).click();
 await expect(page.getByRole('heading',{name:'c-1 · GPU 1枚'})).toBeVisible();
 await page.getByRole('button',{name:'撤去…',exact:true}).click();
 await disposal.getByRole('button',{name:'撤去を確定',exact:true}).click();
 await page.getByRole('tab',{name:'履歴',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Model · m-1',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'撤去設備 c-1',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('保存しました');
 await page.reload();await nav(page,'AI Lab');await page.getByRole('tab',{name:'履歴',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Model · m-1',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'撤去設備 c-1',exact:true})).toBeVisible();
});
